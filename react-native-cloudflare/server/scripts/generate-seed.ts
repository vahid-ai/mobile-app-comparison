/**
 * Generates `server/seed.sql` from `src/core/catalog.ts`.
 *
 * The catalog is transcribed from the Zig core's `const` tables, and this
 * script is what keeps D1 honest about it: the SQL is never hand-edited,
 * it is emitted from the same data the app falls back to offline and the
 * parity tests run against. `npm test` in the app re-runs this in memory
 * and fails if the committed file has drifted.
 *
 *   npm run seed:generate
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CATS, CHATS, EVENTS, GROUPS } from '../../src/core/catalog';

/** SQLite string literal: single quotes double up, and nothing else escapes. */
function q(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function n(value: number): string {
  return String(value);
}

function b(value: boolean): string {
  return value ? '1' : '0';
}

export function buildSeedSql(): string {
  const lines: string[] = [
    '-- Generated by server/scripts/generate-seed.ts — do not edit by hand.',
    '-- Source of truth: src/core/catalog.ts (itself transcribed from the',
    '-- const tables in zero-native/src/core.zig).',
    '',
    'DELETE FROM events;',
    'DELETE FROM categories;',
    'DELETE FROM groups;',
    'DELETE FROM chats;',
    '',
  ];

  lines.push(
    'INSERT INTO events (id, title, venue, area, day, time, time_short, ampm, cat, cat_label, price, free, dist, att, friends, host, host_init, about, pin_left, pin_top, pin_size) VALUES',
  );
  lines.push(
    EVENTS.map(
      (e) =>
        `  (${n(e.id)}, ${q(e.title)}, ${q(e.venue)}, ${q(e.area)}, ${n(e.day)}, ${q(e.time)}, ${q(
          e.timeShort,
        )}, ${q(e.ampm)}, ${q(e.cat)}, ${q(e.catLabel)}, ${q(e.price)}, ${b(e.free)}, ${q(
          e.dist,
        )}, ${n(e.att)}, ${n(e.friends)}, ${q(e.host)}, ${q(e.hostInit)}, ${q(e.about)}, ${n(
          e.pinLeft,
        )}, ${n(e.pinTop)}, ${n(e.pinSize)})`,
    ).join(',\n') + ';',
  );
  lines.push('');

  lines.push('INSERT INTO categories (tag, label, sort) VALUES');
  lines.push(
    CATS.map((c, i) => `  (${q(c.tag)}, ${q(c.label)}, ${n(i)})`).join(',\n') + ';',
  );
  lines.push('');

  lines.push('INSERT INTO groups (id, init, name, members, note) VALUES');
  lines.push(
    GROUPS.map(
      (g) => `  (${n(g.id)}, ${q(g.init)}, ${q(g.name)}, ${n(g.members)}, ${q(g.note)})`,
    ).join(',\n') + ';',
  );
  lines.push('');

  lines.push('INSERT INTO chats (id, init, name, last, "when", unread) VALUES');
  lines.push(
    CHATS.map(
      (c) =>
        `  (${n(c.id)}, ${q(c.init)}, ${q(c.name)}, ${q(c.last)}, ${q(c.when)}, ${n(c.unread)})`,
    ).join(',\n') + ';',
  );
  lines.push('');

  return lines.join('\n');
}

// Only write the file when run directly, so the tests can import
// `buildSeedSql` without touching the tree.
const isMain =
  typeof process !== 'undefined' &&
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) === process.argv[1];

if (isMain) {
  const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'seed.sql');
  writeFileSync(out, buildSeedSql(), 'utf8');
  console.log(`wrote ${out}`);
}
